#!/usr/bin/env python3
"""Stage the conditional timing experiment; never starts a process on the GPU."""
import hashlib
import json
from pathlib import Path
import shutil

HERE = Path(__file__).resolve().parent
QUAL = HERE.parent/'e8-single-logits-qualification-v2'
QUAL_SHA = 'bc2feab326cb67c916ea418b0399499f4986e18d6bba3e4efc7a20a50f0ce030'


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main():
    assert sha(QUAL/'manifest.json') == QUAL_SHA
    frozen = json.loads((QUAL/'manifest.json').read_text())
    dest = HERE/'qualification-source'
    dest.mkdir(exist_ok=True)
    for rel, expected in dict(frozen['files'], **{'manifest.json': QUAL_SHA}).items():
        assert sha(QUAL/rel) == expected, rel
        out = dest/rel; out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(QUAL/rel, out)
    src = (QUAL/'e8_launch.v1.sh').read_text()

    def sub(old, new):
        nonlocal src
        assert src.count(old) == 1, old
        src = src.replace(old, new)

    sub('E8_STAGE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)', '''TIMING_STAGE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
E8_STAGE="$TIMING_STAGE/qualification-source"
: "${E8_TIMING_QUALIFICATION:?completed qualification root required}"
python3 "$TIMING_STAGE/timing_verify.py" --stage "$TIMING_STAGE" --qualification "$E8_TIMING_QUALIFICATION"''')
    sub('"$E8_QUALIFY" == 1', '"$E8_QUALIFY" == 0')
    sub('E8 staging launcher admits qualification only; timing awaits independent review', 'E8 timing requires clean mode and exact prior qualification')
    sub('--qualify --report /logs/e8_shim.json', '--report /logs/e8_shim.json')
    src = src.replace('# E8 qualification-only derivative of byte-pinned E1 v7; generated by e8_prepare.py.', '# E8 clean timing derivative; all arm computations use the unchanged qualified shim/runtime.')
    (HERE/'timing_launch.v1.sh').write_text(src)
    cells = [{'index': i+1, 'block': block+1, 'arm': arm, 'name': f'cell_{i+1:02d}_block{block+1}_{arm}'}
             for block, pair in enumerate([['off','on'],['on','off'],['off','on']]) for i, arm in [(block*2+j, arm) for j, arm in enumerate(pair)]]
    m = {'schema': 'e8.timing.freeze.v1', 'status': 'STAGED_NOT_EXECUTED', 'qualification_manifest_sha256': QUAL_SHA,
         'batch': 1, 'cells': cells, 'no_replacements': True, 'max_cells': 6,
         'model_path': frozen['model_path'], 'model_name': frozen['model_name'], 'image': frozen['image'],
         'checkpoint_identity': frozen['checkpoint_identity'], 'engine_seed': 20260921, 'api_seed': 20260921,
         'temperature': 0, 'max_model_len': 16384, 'gpu_util': 0.6,
         'warmup': {'count': 2, 'prefix': 'pilot[0]', 'max_tokens': 32},
         'timed': {'count': 8, 'max_tokens': 128, 'min_intervals': 8, 'min_intervals_per_prefix': 1},
         'analysis': {'replication_unit': 'paired block', 'primary': 'mean((rate_on_b-rate_off_b)/rate_off_b) over all three blocks',
                      'diagnostic': 'mean(rate_on_b)/mean(rate_off_b)-1', 'bootstrap_draws': 10000,
                      'bootstrap_seed': 20260921, 'bootstrap_rng': 'Python random.Random; three independent randrange(3) indices per draw',
                      'ci': 'percentile 2.5/97.5; linear interpolation at (n-1)*p',
                      'slow_valid_intervals': 'all retained; 1.5s cutoff diagnostic only',
                      'missing_or_insufficient_cell': 'preserve; primary/CI unavailable; no imputation or subset estimate',
                      'extension': 'none, regardless of precision/sign',
                      'predata_supersession': '2026-09-22 parent decision: this timing freeze supersedes only the disabled/provisional ratio-of-means primary carried forward unchanged into qualification-v2 manifestbc2feab3; qualification computations and thresholds are unchanged'},
         'deadlines_seconds': {'launch': 300, 'health': 1500, 'workload': 900, 'subprocess': 180},
         'ownership': {'sampling_seconds': 5, 'scope': 'before/during/after complete warmup+timed workload; host GPU PIDs must be a subset of docker-top host PIDs in the single labeled owned container',
                       'failure': 'query failure, missing owner/GPU PID, foreign container or GPU PID invalidates cell and aborts campaign; no replacement',
                       'limitation': 'sampled telemetry cannot rule out activity entirely between samples'},
         'files': {str(p.relative_to(HERE)): sha(p) for p in sorted(HERE.rglob('*')) if p.is_file() and p.name != 'timing_manifest.json' and '__pycache__' not in str(p) and not str(p.relative_to(HERE)).startswith('tests_out/')}}
    (HERE/'timing_manifest.json').write_text(json.dumps(m, indent=2)+'\n')
    print(json.dumps({'status': 'STAGED', 'files': len(m['files']), 'manifest_sha256': sha(HERE/'timing_manifest.json')}))


if __name__ == '__main__':
    main()
