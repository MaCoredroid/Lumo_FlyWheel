HERE = Path(__file__).resolve().parent
V2 = HERE.parents[1]
REPO = V2.parents[2]
E1 = V2 / "experiments/out-20260922T100028Z-e1-18cells/campaign_snapshot"
D = V2 / "p0/monitor/e1-source-20260922T1150Z"


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    files = ["scripts/fr10_phase4_patch_vllm_tree_gdn.py", "scripts/fr13_device_multidraft_kernel.py",
             "src/lumo_flywheel_serving/fr10_gdn_tree_kernel.py", "src/lumo_flywheel_serving/fr10_decode_modes.py",
             "src/lumo_flywheel_serving/fr13_tree_conv_fused.py", "scripts/gpu_oom_guard.sh"]
    for rel in files:
        out = HERE / "frozen/repository" / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(D / rel, out)
    for name in ["e1_event_recorder_shim.py", "e1_recorder.py", "e1_workload.py", "e1_join.py",
                 "e1_api_tokens_from_capture.v2.py", "prefix_pool.json", "frozen_prefixes.json"]:
        out = HERE / "frozen/e1" / name
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(E1 / name, out)
    base = E1 / "e7a_capture_launch.v7.sh"
    if sha(base) != "a5c398ffff43d1d8ff4678e8df3750987cd520e7710d044cb4cbeb3c1bee7f72":
        raise ValueError("frozen v7 launcher hash mismatch")
    text = base.read_text()
    text = text[text.index("set -euo pipefail"):]

    def sub(old, new, count=1):
        nonlocal text
        if text.count(old) != count:
            raise ValueError("launcher anchor drift: " + old[:80])
        text = text.replace(old, new)

    sub('set -euo pipefail\n\n# REPO IS DERIVED', '''set -euo pipefail
E8_STAGE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
python3 "$E8_STAGE/e8_verify.py" --stage "$E8_STAGE"
: "${REPO:?explicit repository required}" "${CONTAINER:?unique E8 container required}" "${LOG_DIR:?unique E8 run logs required}"
: "${E8_ARM:?on/off required}" "${E8_QUALIFY:?0/1 required}"
[[ "$CONTAINER" == e8-sl-* && "$SEED" == 20260921 && "$E8_QUALIFY" == 1 ]] || { echo 'E8 staging launcher admits qualification only; timing awaits independent review' >&2; exit 2; }
[[ "$E8_ARM" == on || "$E8_ARM" == off ]] || exit 2
# REPO IS DERIVED
''')
    sub('docker rm -f "$CONTAINER" >/dev/null 2>&1 || true', 'if docker inspect "$CONTAINER" >/dev/null 2>&1; then echo "REFUSED: container name exists" >&2; exit 2; fi')
    sub('docker run -d --name "$CONTAINER"', 'docker run -d --label "lumo.e8.run=$E8_RUN_ID" --name "$CONTAINER"')
    sub('  -e FR13_EAGER_PACK="$FR13_EAGER_PACK" \\', '  -e FR13_TREE_RUNROW_INIT="${FR13_TREE_RUNROW_INIT:?E8 requires explicit running-row state policy}" \\\n  -e FR13_EAGER_PACK="$FR13_EAGER_PACK" \\')
    sub('-v "$REPO:/workspace" -v /models:/models:ro -v "$LOG_DIR:/logs" \\', '-v "$REPO:/workspace:ro" -v /models:/models:ro -v "$LOG_DIR:/logs" \\\n  -v "$E8_STAGE:/e8:ro" \\\n' + ''.join('  -v "$E8_STAGE/frozen/repository/' + rel + ':/workspace/' + rel + ':ro" \\\n' for rel in files).rstrip('\n'))
    sub('-e PYTHONPATH=/workspace/src \\', '-e PYTHONPATH=/e8:/workspace/src \\\n  -e PYTHONDONTWRITEBYTECODE=1 \\\n  -e E8_ARM="$E8_ARM" -e E8_QUALIFY="$E8_QUALIFY" -e E8_HEAD_REPORT=/logs/e8_head_gate.json \\\n  -e FR13_FIX1_SELFCHECK="$E8_QUALIFY" -e FR13_FIX1_SELFCHECK_DUMP=/logs/fr13_fix1_selfcheck.json \\')
    anchor='python3 /workspace/scripts/fr10_phase4_patch_vllm_tree_gdn.py\n'
    sub(anchor, anchor + 'python3 /e8/e8_shim.py --arm \\"\\${E8_ARM}\\" --qualify --report /logs/e8_shim.json\n')
    sub('--gpu-memory-utilization \'$GPU_UTIL\' --max-model-len \'$MAX_MODEL_LEN\' \\', '--gpu-memory-utilization \'$GPU_UTIL\' --max-model-len \'$MAX_MODEL_LEN\' --seed \'$SEED\' \\')
    (HERE / "e8_launch.v1.sh").write_text('#!/usr/bin/env bash\n# E8 qualification-only derivative of byte-pinned E1 v7; generated by e8_prepare.py.\n' + text)
    loaded = V2 / "experiments/out-20260922T100028Z-e1-18cells/cell_05_b1_tree_B1_a1/loaded_backend"
    manifest = {
        "schema": "e8.freeze.v1", "status": "STAGED_NOT_EXECUTED", "batch": 1,
        "image": "vllm/vllm-openai@sha256:3dbe092ec5b2cef63b6104d33fa75d6ce53a7870962529ada69f78bbbc38e776",
        "model_path": "/models/qwen3.6-27b-fp8", "model_name": "qwen3.6-27b", "seed": 20260921,
        "checkpoint_identity": "d053823784d5db6f1dbc255bd9ef041e3825efbcfa10ff3e32011671e979c578",
        "engine_seed": 20260921, "temperature": 0, "qualification_order": ["on", "off"],
        "qualification_prefixes": 8, "qualification_max_tokens": 32,
        "deadlines_seconds": {"launch": 300, "health": 1500, "workload_per_arm": 600, "other_subprocess": 180},
        "clean_timing": {"enabled": False, "reason": "independent review and successful qualification required",
            "blocks": [["off", "on"], ["on", "off"], ["off", "on"]],
            "warmup": {"requests": 2, "prompt": "pilot[0]", "max_tokens": 32},
            "timed": {"requests": 8, "max_tokens": 128}, "min_intervals": 8, "min_per_prefix": 1,
            "max_cells": 6, "no_replacements": True, "replication_unit": "paired block",
            "contrast": "mean(cell_rate_on)/mean(cell_rate_off)-1; ratio of arm means, not mean of block ratios", "bootstrap": "10000 paired-block draws, seed20260921; recompute ratio of arm means each draw; three blocks coarse",
            "slow_valid_intervals": "retain", "api_stream_differences": "report; not a same-input correctness failure"},
        "unchanged_loaded_modules": {p.name: sha(p) for p in loaded.glob('*.py') if p.name != 'eagle.py'},
        "eagle_variants": {arm + ('_qualification' if qualify else '_clean'): hashlib.sha256(render((loaded / 'eagle.py').read_bytes(), arm, qualify)[0]).hexdigest()
                           for arm in ('on', 'off') for qualify in (True, False)},
        "files": {str(p.relative_to(HERE)): sha(p) for p in sorted(HERE.rglob('*')) if p.is_file() and p.name != 'manifest.json' and '__pycache__' not in str(p) and not str(p.relative_to(HERE)).startswith('tests_out/')},
    }
    (HERE / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps({'stage': str(HERE), 'files': len(manifest['files']), 'manifest_sha256': sha(HERE/'manifest.json')}))


if __name__ == '__main__':
    main()
